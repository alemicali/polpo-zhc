import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

async function readJson(path) {
  return JSON.parse(await readFile(resolve(root, path), "utf8"));
}

function subset(source, names) {
  const result = {
    prefix: source.prefix,
    icons: {},
    width: source.width,
    height: source.height,
  };

  function include(name) {
    if (source.icons[name]) {
      result.icons[name] = source.icons[name];
      return;
    }
    const alias = source.aliases?.[name];
    if (!alias) throw new Error(`Icon ${source.prefix}:${name} does not exist`);
    result.aliases ??= {};
    result.aliases[name] = alias;
    include(alias.parent);
  }

  for (const name of names) include(name);
  return result;
}

const sourceFiles = [
  "src/components/shared/channel-logo.tsx",
  "src/pages/coding/empty-quickstart.tsx",
  "src/pages/coding/new-terminal-dialog.tsx",
  "src/pages/coding/session-tabs.tsx",
  "src/pages/coding/file-icon.tsx",
];
const source = (await Promise.all(sourceFiles.map((path) => readFile(resolve(root, path), "utf8")))).join("\n");
const namesFor = (prefix) => [...new Set(
  [...source.matchAll(new RegExp(`${prefix}:([A-Za-z0-9_-]+)`, "g"))].map((match) => match[1]),
)].sort();

// resolved as the UI's own dependencies: works with or without a hoisted root node_modules (Docker)
const require = createRequire(import.meta.url);
const [logos, vscodeIcons] = await Promise.all([
  readJson(require.resolve("@iconify-json/logos/icons.json")),
  readJson(require.resolve("@iconify-json/vscode-icons/icons.json")),
]);
const generated = `// Generated by scripts/generate-icon-subsets.mjs. Do not edit.\n`
  + `export const logosSubset = ${JSON.stringify(subset(logos, namesFor("logos")))};\n`
  + `export const vscodeIconsSubset = ${JSON.stringify(subset(vscodeIcons, namesFor("vscode-icons")))};\n`;

const output = resolve(root, "src/generated/icon-subsets.ts");
await mkdir(dirname(output), { recursive: true });
await writeFile(output, generated);
console.log(`Generated ${namesFor("logos").length} logo and ${namesFor("vscode-icons").length} file icons`);
