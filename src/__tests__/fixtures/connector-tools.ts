/**
 * Realistic connector tool sets for progressive discovery tests: names, titles and descriptions
 * shaped like the real MCP servers (Linear 78 tools, Gmail 23, GitHub 46, Slack 27), bridged the
 * way src/mcp/tools.ts does it (`mcp__<id>__<tool>`, label "<connector>: <title>", description
 * "[<connector>] …").
 */

export interface FixtureTool {
  name: string;
  label: string;
  description: string;
  parameters: { type: "object"; properties: Record<string, unknown> };
}

type Spec = [tool: string, description: string, params?: string[]];

const humanize = (name: string) => name.replace(/_/g, " ").replace(/^./, (c) => c.toUpperCase());

export function bridge(connectorId: string, connectorLabel: string, specs: Spec[]): FixtureTool[] {
  return specs.map(([tool, description, params = []]) => ({
    name: `mcp__${connectorId}__${tool}`,
    label: `${connectorLabel}: ${humanize(tool)}`,
    description: `[${connectorLabel}] ${description}`,
    parameters: { type: "object", properties: Object.fromEntries(params.map((p) => [p, { type: "string" }])) },
  }));
}

