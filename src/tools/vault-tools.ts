/**
 * Vault tools for agents to access their own credentials at runtime.
 *
 * Provides read-only access to the agent's resolved vault:
 * - vault_get: retrieve credentials for a specific service
 * - vault_list: list available services (keys only, values masked)
 *
 * The vault is pre-resolved at spawn time — ${ENV_VAR} references are already
 * replaced with actual values. Agents can only see their own credentials.
 *
 * Sandboxed runs (any provider but "local"): vault_get does not return secret values. It shows
 * the entry's type, label, key names and the non-secret fields (NON_SECRET_VAULT_FIELDS), and
 * points to bash's env_from_vault, which hands the values to one command and masks them in its
 * output. Tools that use the vault internally (email, image, storage…) are unaffected.
 */

import { Type } from "typebox";
import type { AgentTool } from "@earendil-works/pi-agent-core";
import {
  allowedToolsInclude, generateVaultLogin, vaultLoginFillHint, VAULT_PASSWORD_DEFAULT_LENGTH, VAULT_PASSWORD_MAX_LENGTH, VAULT_PASSWORD_MIN_LENGTH,
  type VaultLoginRequest, type VaultLoginResult,
} from "@polpo-ai/core";
import type { VaultStore } from "@polpo-ai/core/vault-store";
import type { ResolvedVault } from "../vault/index.js";
import { isNonSecretVaultField, suggestedEnvVarName, SECRET_MASK, type RunSecrets } from "../vault/env-from-vault.js";

export interface VaultToolsOptions {
  /**
   * The effective sandbox provider of the run. Anything but "local" (bwrap, docker, daytona, e2b)
   * hides secret values from vault_get. Undefined = no sandbox (as "local").
   */
  sandboxProvider?: string;
}

/** True when secrets reach commands only through env_from_vault (sandboxed runs). */
export function vaultSecretsHidden(sandboxProvider: string | undefined): boolean {
  return !!sandboxProvider && sandboxProvider !== "local";
}

// ─── Tool names ───

export const ALL_VAULT_TOOL_NAMES = ["vault_get", "vault_list"] as const;
export type VaultToolName = (typeof ALL_VAULT_TOOL_NAMES)[number];

// ─── Tool: vault_get ───

const VaultGetSchema = Type.Object({
  service: Type.String({ description: "Service name to retrieve credentials for (e.g. 'smtp', 'openai', 'stripe')" }),
});

function createVaultGetTool(vault: ResolvedVault, opts: VaultToolsOptions = {}): AgentTool<typeof VaultGetSchema> {
  const hidden = vaultSecretsHidden(opts.sandboxProvider);
  return {
    name: "vault_get",
    label: "Get Vault Credentials",
    description: hidden
      ? "Describe a service in your vault: its type, label, credential key names and non-secret fields (host, port, user…). "
        + "Secret values are not returned in this sandbox: to use them in a command, pass them to bash with env_from_vault "
        + "(e.g. {\"GITHUB_TOKEN\": \"github.token\"}) and reference $GITHUB_TOKEN in the command. Use vault_list first to see available services."
      : "Retrieve credentials for a specific service from your vault. Returns all credential key-value pairs for the requested service. Use vault_list first to see available services.",
    parameters: VaultGetSchema,
    async execute(_toolCallId, params) {
      const creds = vault.get(params.service);
      if (!creds) {
        return {
          content: [{ type: "text", text: `No vault entry found for service "${params.service}". Use vault_list to see available services.` }],
          details: { service: params.service, found: false },
        };
      }
      const generated = new Set(vault.generatedKeys?.(params.service) ?? []);
      if (hidden || generated.size > 0) {
        const info = vault.list().find((s) => s.service === params.service);
        const secretKeys: string[] = [];
        const lines = Object.entries(creds).map(([key, value]) => {
          // hidden: only non-secret fields; otherwise only the values Polpo generated stay masked
          const show = hidden ? isNonSecretVaultField(key, value) && !generated.has(key) : !generated.has(key);
          if (show) return `  ${key}: ${value}`;
          secretKeys.push(key);
          return `  ${key}: ${SECRET_MASK}`;
        });
        const example = secretKeys[0] ?? Object.keys(creds)[0];
        const header = `Vault entry "${params.service}" (${info?.type ?? "custom"}${info?.label ? `, label: ${info.label}` : ""}):`;
        const hint = !hidden
          ? `${[...generated].join(", ")} ${generated.size === 1 ? "was" : "were"} generated by Polpo and ${generated.size === 1 ? "is" : "are"} never shown: `
            + `fill ${generated.size === 1 ? "it" : "them"} with browser_fill { from_vault: "${params.service}.${[...generated][0]}" } `
            + `or pass ${generated.size === 1 ? "it" : "them"} to a command with bash's env_from_vault.`
          : example
          ? `Secret values are not shown in sandboxed runs. To use one in a command, call bash with env_from_vault, e.g. `
            + `{"${suggestedEnvVarName(params.service, example)}": "${params.service}.${example}"}, and reference $${suggestedEnvVarName(params.service, example)} in the command: `
            + `the value exists only in that command's environment and appears as ${SECRET_MASK} in its output. Do not write it to files.`
          : "";
        return {
          content: [{ type: "text", text: [header, ...lines, ...(hint ? ["", hint] : [])].join("\n") }],
          details: { service: params.service, found: true, keys: Object.keys(creds), secretsHidden: true, ...(generated.size ? { generated: [...generated] } : {}) },
        };
      }
      const lines = Object.entries(creds).map(([key, value]) => `  ${key}: ${value}`);
      return {
        content: [{ type: "text", text: `Credentials for "${params.service}":\n${lines.join("\n")}` }],
        details: { service: params.service, found: true, keys: Object.keys(creds) },
      };
    },
  };
}

// ─── Tool: vault_list ───

const VaultListSchema = Type.Object({});

function createVaultListTool(vault: ResolvedVault, opts: VaultToolsOptions = {}): AgentTool<typeof VaultListSchema> {
  const hidden = vaultSecretsHidden(opts.sandboxProvider);
  return {
    name: "vault_list",
    label: "List Vault Services",
    description: hidden
      ? "List all available services in your vault. Shows service names, types, and credential key names (values are not shown). In this sandbox, commands get secret values through bash's env_from_vault (\"service.key\")."
      : "List all available services in your vault. Shows service names, types, and credential key names (values are not shown). Use vault_get to retrieve actual credential values.",
    parameters: VaultListSchema,
    async execute() {
      const services = vault.list();
      if (services.length === 0) {
        return {
          content: [{ type: "text", text: "No vault entries configured for this agent." }],
          details: { count: 0, services: [] },
        };
      }
      const lines = services.map(s => `  - ${s.service} (${s.type}): keys=[${s.keys.join(", ")}]`);
      const hint = hidden ? `\nSecret values reach commands only through bash's env_from_vault, e.g. {"VAR": "service.key"}.` : "";
      return {
        content: [{ type: "text", text: `${services.length} vault service(s):\n${lines.join("\n")}${hint}` }],
        details: { count: services.length, services: services.map(s => s.service) },
      };
    },
  };
}

// ─── Tool: vault_create_login ───

export const VAULT_CREATE_LOGIN_TOOL = "vault_create_login";
export const VAULT_LOGIN_TOOL_NAMES = [VAULT_CREATE_LOGIN_TOOL] as const;

/** Is vault_create_login granted (allowedTools "vault_create_login", "vault_*", …)? */
export function agentHasVaultLoginTool(agent: { allowedTools?: string[] }): boolean {
  return allowedToolsInclude(agent.allowedTools, VAULT_CREATE_LOGIN_TOOL);
}

/**
 * How a run creates a login: in the server process with the vault store directly; from a task run
 * over the notification socket (the server takes the agent from the run record). The owner is
 * never part of the request.
 */
export interface VaultLoginAccess {
  create(req: VaultLoginRequest): Promise<VaultLoginResult>;
}

/** The access in the server process (chats, agent tests): the agent's own vault, with where the call came from. */
export function localVaultLoginAccess(
  store: Pick<VaultStore, "get" | "set">,
  agent: { name: string; identity?: { displayName?: string } },
  origin: { taskId?: string; sessionId?: string; runId?: string } | (() => { taskId?: string; sessionId?: string; runId?: string }) = {},
): VaultLoginAccess {
  return {
    create: (req) => {
      const o = typeof origin === "function" ? origin() : origin;
      return generateVaultLogin(store, agent.name, req, {
        kind: "agent", agent: agent.name,
        ...(o.taskId ? { taskId: o.taskId } : {}), ...(o.sessionId ? { sessionId: o.sessionId } : {}), ...(o.runId ? { runId: o.runId } : {}),
      }, { ...(agent.identity?.displayName ? { ownerDisplayName: agent.identity.displayName } : {}) });
    },
  };
}

const VaultCreateLoginSchema = Type.Object({
  service: Type.String({ description: "A short slug for the site's vault entry (letters, digits, _ or -), e.g. \"sitoinchat\"" }),
  username: Type.Optional(Type.String({ description: "The account's username, if the site uses one" })),
  email: Type.Optional(Type.String({ description: "The account's email, if the site signs up with an email" })),
  url: Type.Optional(Type.String({ description: "The site (https://…)" })),
  label: Type.Optional(Type.String({ description: "A label for people (default: \"<Service> – <your name>\")" })),
  length: Type.Optional(Type.Integer({ minimum: VAULT_PASSWORD_MIN_LENGTH, maximum: VAULT_PASSWORD_MAX_LENGTH, description: `Password length (default ${VAULT_PASSWORD_DEFAULT_LENGTH})` })),
  symbols: Type.Optional(Type.Boolean({ description: "Include symbols (default true); false for sites that reject them" })),
  rotate: Type.Optional(Type.Boolean({ description: "Replace the password of an existing login of yours (keeps username, email and url). Default false." })),
});

/**
 * vault_create_login: a new login in the agent's own vault with a password Polpo generates. The
 * model never sees the password: the result has only the key names and how to fill it; the value
 * goes to the run's masker and the run's vault (browser_fill / env_from_vault find it at once).
 */
export function createVaultLoginTools(
  agent: { name: string; allowedTools?: string[] },
  access: VaultLoginAccess | undefined,
  opts: { vault?: ResolvedVault; secrets?: RunSecrets } = {},
): AgentTool<any>[] {
  if (!access || !agentHasVaultLoginTool(agent)) return [];
  const tool: AgentTool<typeof VaultCreateLoginSchema> = {
    name: VAULT_CREATE_LOGIN_TOOL,
    label: "Create Vault Login",
    description: "Create a new login (account credentials) in your own vault with a strong password Polpo generates. "
      + "You never see the password: fill it into the sign-up / login form with browser_fill { from_vault: \"<service>.password\" } "
      + "(or pass it to a command with bash's env_from_vault). Refuses an existing entry unless rotate: true. "
      + "Use it when you sign up for a site; never invent passwords yourself.",
    parameters: VaultCreateLoginSchema,
    async execute(_id, params) {
      const fail = (text: string) => ({ content: [{ type: "text" as const, text: `Error: ${text}` }], details: { error: true } });
      let r: VaultLoginResult;
      try {
        r = await access.create({
          service: String(params.service ?? "").trim(),
          ...(typeof params.username === "string" ? { username: params.username } : {}),
          ...(typeof params.email === "string" ? { email: params.email } : {}),
          ...(typeof params.url === "string" ? { url: params.url } : {}),
          ...(typeof params.label === "string" ? { label: params.label } : {}),
          ...(typeof params.length === "number" ? { length: params.length } : {}),
          ...(typeof params.symbols === "boolean" ? { symbols: params.symbols } : {}),
          ...(params.rotate === true ? { rotate: true } : {}),
        });
      } catch (err) {
        return fail(err instanceof Error ? err.message : String(err));
      }
      if (!r.ok) return fail(r.error);
      // the value: masked from now on, and usable at once in this run
      for (const key of r.metadata.generated ?? ["password"]) {
        const v = r.credentials[key];
        if (v) opts.secrets?.add(v);
      }
      opts.vault?.upsert?.(r.service, { type: "login", ...(r.label ? { label: r.label } : {}), credentials: r.credentials, metadata: r.metadata });
      const fill = vaultLoginFillHint(r.service);
      const ids = r.keys.filter((k) => k !== "password" && k !== "url").map((k) => `${k}: ${r.credentials[k]}`);
      return {
        content: [{
          type: "text" as const,
          text: `Login "${r.service}" ${r.action} in your vault (keys: ${r.keys.join(", ")}${ids.length ? `; ${ids.join(", ")}` : ""}). `
            + `The password was generated by Polpo and is never shown: fill it with ${fill}.`,
        }],
        details: { service: r.service, keys: r.keys, [r.action]: true, action: r.action, fill },
      };
    },
  };
  return [tool];
}

// ─── Factory ───

/**
 * Create vault tools (core — always included when vault is available).
 * Vault tools are core tools: they are always available to every agent
 * that has a resolved vault, regardless of allowedTools configuration.
 */
export function createVaultToolsCore(vault: ResolvedVault, opts: VaultToolsOptions = {}): AgentTool<any>[] {
  return [createVaultGetTool(vault, opts), createVaultListTool(vault, opts)];
}

/**
 * Create vault tools for an agent, filtered by allowedTools.
 * @deprecated Use createVaultToolsCore() — vault tools are now core tools (always available).
 */
export function createVaultTools(vault: ResolvedVault, allowedTools?: string[], opts: VaultToolsOptions = {}): AgentTool<any>[] {
  const tools: AgentTool<any>[] = [];
  const allowed = (name: string) => !allowedTools || allowedTools.includes(name);

  if (allowed("vault_get")) tools.push(createVaultGetTool(vault, opts));
  if (allowed("vault_list")) tools.push(createVaultListTool(vault, opts));

  return tools;
}
