/**
 * Builds the MCP App widgets (widgets/<name>/main.ts + style.css) into single HTML documents and
 * writes them, as strings, to src/server/mcp-widgets.generated.ts: the server (and the desktop app's
 * compiled server) serves them without reading files at run time.
 *
 *   node widgets/build.mjs           write the generated module
 *   node widgets/build.mjs --check   fail if it is not up to date (also a test)
 */
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const GENERATED = join(here, "..", "src", "server", "mcp-widgets.generated.ts");

/** name → exported constant */
const WIDGETS = { "agent-card": "AGENT_CARD_HTML" };

async function widgetHtml(name) {
  const dir = join(here, name);
  const out = await build({
    entryPoints: [join(dir, "main.ts")],
    bundle: true,
    minify: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    write: false,
    legalComments: "none",
    logLevel: "silent",
  });
  const js = out.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
  const css = (await readFile(join(dir, "style.css"), "utf-8")).replace(/<\/style/gi, "<\\/style");
  return `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="color-scheme" content="light dark"><style>${css}</style></head><body><div id="root"></div><script type="module">${js}</script></body></html>`;
}

export async function generatedModule() {
  const parts = ["// Generated by widgets/build.mjs from widgets/*: do not edit. Rebuild with `pnpm run build:widgets`.\n"];
  for (const [name, constant] of Object.entries(WIDGETS)) {
    parts.push(`export const ${constant} = ${JSON.stringify(await widgetHtml(name))};\n`);
  }
  return parts.join("");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = await generatedModule();
  if (process.argv.includes("--check")) {
    const current = await readFile(GENERATED, "utf-8").catch(() => "");
    if (current !== next) {
      console.error("src/server/mcp-widgets.generated.ts is out of date: run `pnpm run build:widgets`");
      process.exit(1);
    }
  } else {
    await writeFile(GENERATED, next);
    console.log(`wrote ${GENERATED} (${(next.length / 1024).toFixed(0)} KB)`);
  }
}
