#!/usr/bin/env node
/**
 * Bundle the connector catalog's official icons into the dashboard (no runtime hotlinking):
 *
 *   node scripts/fetch-connector-icons.mjs [--force]
 *
 * For each entry of src/mcp/catalog-data.ts it writes ui/public/connector-icons/<id>.<ext>:
 *   1. the `simple-icons` slug, rendered with the entry's brand color;
 *   2. else the vendor's SVG (`icon.svg`), downloaded and sanitized (no scripts, no handlers);
 *   3. else the vendor's PNG / favicon (`icon.png`), saved with its real format (.png, .ico, .jpg…).
 * Entries with nothing usable get no file: the UI falls back to a letter avatar with the brand
 * color. Existing files are kept unless --force. Run once after the catalog changes; commit the
 * output (and ui/src/generated/connector-icons.ts, which tells the UI which file each entry has, and
 * src/mcp/catalog-icons.generated.ts, the same for the server).
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as simpleIcons from "simple-icons";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "ui", "public", "connector-icons");
const force = process.argv.includes("--force");

const source = readFileSync(join(root, "src", "mcp", "catalog-data.ts"), "utf-8");
const json = source.slice(source.indexOf("= [") + 2, source.lastIndexOf("];") + 1);
/** @type {Array<{ id: string; name: string; icon?: { simpleIcons?: string | null; svg?: string | null; png?: string | null } | null; brandColor?: string | null }>} */
const entries = JSON.parse(json);

const bySlug = new Map();
for (const value of Object.values(simpleIcons)) {
  if (value && typeof value === "object" && "slug" in value && "path" in value) bySlug.set(value.slug, value);
}

const MAX_BYTES = 256 * 1024;
const UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130 Safari/537.36";

async function download(url) {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), 15_000);
  try {
    const res = await fetch(url, { signal: ctrl.signal, redirect: "follow", headers: { "user-agent": UA, accept: "image/svg+xml,image/png,image/*;q=0.8,*/*;q=0.5" } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length === 0) throw new Error("empty");
    if (buf.length > MAX_BYTES) throw new Error(`too large (${buf.length} bytes)`);
    return buf;
  } finally {
    clearTimeout(timer);
  }
}

/** Keep a vendor SVG only if it is an SVG; drop scripts, event handlers, external references. */
function sanitizeSvg(text) {
  const start = text.search(/<svg[\s>]/i);
  if (start < 0 || !/<\/svg>\s*$/i.test(text.trim())) throw new Error("not an SVG");
  return text.slice(start)
    .replace(/<script[\s\S]*?<\/script>/gi, "")
    .replace(/<foreignObject[\s\S]*?<\/foreignObject>/gi, "")
    .replace(/\son[a-z]+\s*=\s*("[^"]*"|'[^']*')/gi, "")
    .replace(/(href\s*=\s*)("|')\s*javascript:[^"']*\2/gi, "$1$2#$2")
    .trim() + "\n";
}

/** The raster format of a downloaded icon (by magic bytes), or undefined. */
function rasterType(buf) {
  const head = (bytes) => buf.length > bytes.length && buf.subarray(0, bytes.length).equals(Buffer.from(bytes));
  if (head([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) return "png";
  if (head([0x00, 0x00, 0x01, 0x00])) return "ico";
  if (head([0xff, 0xd8, 0xff])) return "jpg";
  if (head([0x47, 0x49, 0x46, 0x38])) return "gif";
  if (head([0x52, 0x49, 0x46, 0x46]) && buf.subarray(8, 12).toString("latin1") === "WEBP") return "webp";
  return undefined;
}

function simpleIconSvg(icon, color) {
  const fill = /^#?[0-9a-f]{6}$/i.test(color ?? "") ? `#${color.replace("#", "")}` : `#${icon.hex}`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" role="img"><title>${icon.title.replace(/[<&>]/g, "")}</title><path fill="${fill}" d="${icon.path}"/></svg>\n`;
}

mkdirSync(outDir, { recursive: true });
const indexPath = join(root, "ui", "src", "generated", "connector-icons.ts");
const INDEX_HEADER = [
  "// Generated by scripts/fetch-connector-icons.mjs — do not edit by hand.",
  "// Which bundled icon file (ui/public/connector-icons/<id>.<ext>) each catalog entry has.",
  "export const CONNECTOR_ICON_FILES: Record<string, string> = ",
].join("\n");
const index = existsSync(indexPath) && !force
  ? JSON.parse(readFileSync(indexPath, "utf-8").replace(/^[^{]*/, "").replace(/;\s*$/, ""))
  : {};
const failed = [];
const counts = { simpleIcons: 0, svg: 0, raster: 0, kept: 0 };

async function one(entry) {
  const file = (ext) => join(outDir, `${entry.id}.${ext}`);
  if (!force && index[entry.id] && existsSync(file(index[entry.id]))) {
    counts.kept++;
    return;
  }
  const save = (ext, data, kind) => {
    writeFileSync(file(ext), data);
    index[entry.id] = ext;
    counts[kind]++;
  };
  const errors = [];
  const slug = entry.icon?.simpleIcons;
  if (slug) {
    const icon = bySlug.get(slug);
    if (icon) return save("svg", simpleIconSvg(icon, entry.brandColor), "simpleIcons");
    errors.push(`simple-icons "${slug}" not found`);
  }
  for (const key of ["svg", "png"]) {
    const url = entry.icon?.[key];
    if (!url) continue;
    try {
      const buf = await download(url);
      const raster = rasterType(buf);
      if (raster) return save(raster, buf, "raster");
      return save("svg", sanitizeSvg(buf.toString("utf-8")), "svg");
    } catch (err) {
      errors.push(`${key}: ${err instanceof Error ? err.message : err}`);
    }
  }
  delete index[entry.id];
  failed.push(`${entry.id}: ${errors.join("; ") || "no icon in the catalog"}`);
}

// a few downloads at a time
const queue = [...entries];
await Promise.all(Array.from({ length: 8 }, async () => {
  for (let entry = queue.shift(); entry; entry = queue.shift()) await one(entry);
}));

// drop files of entries that left the catalog (or changed extension)
for (const file of readdirSync(outDir)) {
  const ext = file.split(".").pop();
  const id = file.slice(0, -(ext.length + 1));
  if (index[id] !== ext) unlinkSync(join(outDir, file));
}
const sorted = Object.fromEntries(Object.entries(index).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(indexPath, `${INDEX_HEADER}${JSON.stringify(sorted, null, 2)};\n`);
// the same map for the server (the API's iconUrl and the MCP connector's icon_url)
writeFileSync(join(root, "src", "mcp", "catalog-icons.generated.ts"), [
  "// Generated by scripts/fetch-connector-icons.mjs — do not edit by hand.",
  "// Which bundled dashboard icon file (ui/public/connector-icons/<id>.<ext>) each catalog entry has.",
  `export const CATALOG_ICON_FILES: Record<string, string> = ${JSON.stringify(sorted, null, 2)};\n`,
].join("\n"));

console.log(`Icons: ${counts.simpleIcons} simple-icons, ${counts.svg} vendor SVG, ${counts.raster} PNG/ICO/other, ${counts.kept} kept; ${failed.length} without an icon.`);
for (const line of failed) console.log(`  - ${line}`);
