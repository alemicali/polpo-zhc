#!/usr/bin/env node
/**
 * Regenerate src/mcp/catalog-data.ts from a verified catalog JSON (array of
 * {id, name, category, description, url, transport, auth, oauthRegistration, authNotes,
 *  urlTemplate, docs, domain, inClaudeDirectory, inLovable, verified, icon, brandColor}).
 *
 *   node scripts/generate-connector-catalog.mjs path/to/mcp-catalog.json
 *
 * The data is kept as-is; src/mcp/catalog.ts turns it into ConnectorCatalogEntry (OAuth apps,
 * Google scopes, region variants, URL templates).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/generate-connector-catalog.mjs <mcp-catalog.json>");
  process.exit(1);
}
const entries = JSON.parse(readFileSync(input, "utf-8"));
if (!Array.isArray(entries)) throw new Error("The catalog must be a JSON array");
const ids = new Set();
for (const e of entries) {
  for (const key of ["id", "name", "category", "url", "transport", "auth"]) {
    if (typeof e[key] !== "string" || !e[key]) throw new Error(`Entry ${e.id ?? "?"}: missing ${key}`);
  }
  if (ids.has(e.id)) throw new Error(`Duplicate id ${e.id}`);
  ids.add(e.id);
}
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "mcp", "catalog-data.ts");
writeFileSync(out, [
  "// Generated by scripts/generate-connector-catalog.mjs — do not edit by hand.",
  "// Official remote MCP servers (vendor docs, Claude's directory, Lovable, the MCP registry).",
  'import type { RawCatalogEntry } from "./catalog.js";',
  "",
  `export const CATALOG_DATA: RawCatalogEntry[] = ${JSON.stringify(entries, null, 2)};`,
  "",
].join("\n"));
console.log(`Wrote ${entries.length} entries to ${out}`);
