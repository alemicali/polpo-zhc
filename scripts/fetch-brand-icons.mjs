#!/usr/bin/env node
/**
 * Bundle the official marks the dashboard shows for where and with what a run executes
 * (engines, auth providers, computers, egress) — no runtime hotlinking:
 *
 *   node scripts/fetch-brand-icons.mjs [--force]
 *
 * - Vector marks from `simple-icons` (Claude, Claude Code, Anthropic, Tailscale, Google Cloud, OpenCode)
 *   → ui/src/generated/brand-icons.ts (path + brand colour; rendered inline by <BrandIcon>).
 * - The vendors' own marks where simple-icons has none (Daytona: its light and dark favicons;
 *   E2B: its app icon) → ui/public/brand-icons/<name>.png.
 * - OpenAI (Codex), Amazon Bedrock and Vertex AI come from @lobehub/icons, already a dependency
 *   of the dashboard (ui/src/components/shared/brand-icon.tsx loads them lazily).
 *
 * Existing PNGs are kept unless --force. Commit the output.
 */
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as simpleIcons from "simple-icons";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const force = process.argv.includes("--force");

/** BrandIcon name → simple-icons slug. */
const VECTOR = {
  claude: "claude",
  "claude-code": "claudecode",
  anthropic: "anthropic",
  tailscale: "tailscale",
  "google-cloud": "googlecloud",
  opencode: "opencode",
};

/** BrandIcon file → the vendor's official mark. */
const RASTER = {
  "daytona-light": "https://framerusercontent.com/images/6WPclDLAHHQgPFeA2DRTW1OXVSU.png",
  "daytona-dark": "https://framerusercontent.com/images/cCvSUNbGejoZpWVg0tUGLSqxGC8.png",
  e2b: "https://e2b.dev/icon2.png",
};

const bySlug = new Map();
for (const value of Object.values(simpleIcons)) {
  if (value && typeof value === "object" && "slug" in value && "path" in value) bySlug.set(value.slug, value);
}

const vectors = {};
for (const [name, slug] of Object.entries(VECTOR)) {
  const icon = bySlug.get(slug);
  if (!icon) throw new Error(`simple-icons has no "${slug}"`);
  vectors[name] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
}
const out = join(root, "ui", "src", "generated", "brand-icons.ts");
writeFileSync(out, [
  "// Generated by scripts/fetch-brand-icons.mjs — do not edit by hand.",
  "// Official vector marks (simple-icons, CC0): 24×24 path and brand colour.",
  "export interface BrandVector { title: string; hex: string; path: string }",
  `export const BRAND_VECTORS: Record<${Object.keys(vectors).map((k) => JSON.stringify(k)).join(" | ")}, BrandVector> = ${JSON.stringify(vectors, null, 2)};`,
  "",
].join("\n"));
console.log(`wrote ${out}`);

const pngDir = join(root, "ui", "public", "brand-icons");
mkdirSync(pngDir, { recursive: true });
for (const [name, url] of Object.entries(RASTER)) {
  const file = join(pngDir, `${name}.png`);
  if (existsSync(file) && !force) { console.log(`kept ${file}`); continue; }
  const res = await fetch(url, { redirect: "follow" });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (!buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) throw new Error(`${url}: not a PNG`);
  writeFileSync(file, buf);
  console.log(`wrote ${file} (${buf.length} bytes)`);
}
